// Purpose: EF Core database context for the app: scheduling tables (technicians, jobs, assignments,
// buildings, file metadata) plus the ASP.NET Core Identity tables for users and roles.
using FireAlarmScheduler.Entities;
using Microsoft.AspNetCore.Identity.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore;

namespace FireAlarmScheduler.Data;

public class AppDbContext(DbContextOptions<AppDbContext> options) : IdentityDbContext<ApplicationUser>(options)
{
    public DbSet<Technician> Technicians => Set<Technician>();
    public DbSet<Job> Jobs => Set<Job>();
    public DbSet<JobAssignment> JobAssignments => Set<JobAssignment>();
    public DbSet<Building> Buildings => Set<Building>();
    public DbSet<UploadedFile> UploadedFiles => Set<UploadedFile>();

    /// <summary>
    /// Ids are generated by the services (Guid.NewGuid), so they are marked ValueGeneratedNever; this makes
    /// EF Core insert new child rows added to a loaded job instead of treating them as existing rows.
    /// </summary>
    protected override void OnModelCreating(ModelBuilder builder)
    {
        base.OnModelCreating(builder);

        builder.Entity<Technician>(e =>
        {
            e.Property(t => t.Id).ValueGeneratedNever();
            e.Property(t => t.FirstName).HasMaxLength(100);
            e.Property(t => t.LastName).HasMaxLength(100);
            e.Ignore(t => t.FullName);
        });

        builder.Entity<Job>(e =>
        {
            e.Property(j => j.Id).ValueGeneratedNever();
            e.Property(j => j.Name).HasMaxLength(200);
            e.Property(j => j.CustomerName).HasMaxLength(200);
            e.Property(j => j.SiteName).HasMaxLength(200);
            e.Property(j => j.Address).HasMaxLength(300);
            e.Property(j => j.Notes).HasMaxLength(4000);
            e.Property(j => j.Status).HasConversion<string>().HasMaxLength(20);
            e.Ignore(j => j.AssignedTechnicianIds);
            e.HasIndex(j => j.StartDate);
            e.HasMany(j => j.Assignments).WithOne().HasForeignKey(a => a.JobId).OnDelete(DeleteBehavior.Cascade);
            e.HasMany(j => j.Buildings).WithOne().HasForeignKey(b => b.JobId).OnDelete(DeleteBehavior.Cascade);
        });

        // Deleting a technician removes their assignments; deleting a job removes its assignments.
        builder.Entity<JobAssignment>(e =>
        {
            e.HasKey(a => new { a.JobId, a.TechnicianId });
            e.HasOne<Technician>().WithMany().HasForeignKey(a => a.TechnicianId).OnDelete(DeleteBehavior.Cascade);
        });

        builder.Entity<Building>(e =>
        {
            e.Property(b => b.Id).ValueGeneratedNever();
            e.Property(b => b.Name).HasMaxLength(100);
            e.Property(b => b.Notes).HasMaxLength(2000);
            e.HasMany(b => b.UploadedFiles).WithOne().HasForeignKey(f => f.BuildingId).OnDelete(DeleteBehavior.Cascade);
        });

        builder.Entity<UploadedFile>(e =>
        {
            e.Property(f => f.Id).ValueGeneratedNever();
            e.Property(f => f.OriginalFileName).HasMaxLength(150);
            e.Property(f => f.StoredFileName).HasMaxLength(100);
            e.HasIndex(f => f.StoredFileName).IsUnique();
        });

        // A technician record can be linked to at most one sign-in account.
        builder.Entity<ApplicationUser>(e =>
        {
            e.Property(u => u.DisplayName).HasMaxLength(100);
            e.HasOne<Technician>().WithMany().HasForeignKey(u => u.TechnicianId).OnDelete(DeleteBehavior.SetNull);
            e.HasIndex(u => u.TechnicianId).IsUnique();
        });
    }
}
